import uuid
from datetime import date, datetime
from typing import Annotated

from pydantic import AwareDatetime, BaseModel, ConfigDict, StringConstraints, field_validator

from app.models import Task

Title = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1)]


class TaskOut(BaseModel):
    id: uuid.UUID
    voice_entry_id: uuid.UUID | None
    title: str
    note: str | None
    starred: bool
    due_date: date | None
    remind_at: datetime | None
    my_day: bool
    completed: bool
    completed_at: datetime | None
    created_at: datetime | None
    updated_at: datetime | None

    @classmethod
    def from_model(cls, task: Task, today: date) -> "TaskOut":
        return cls(
            id=task.id,
            voice_entry_id=task.voice_entry_id,
            title=task.title,
            note=task.note,
            starred=task.starred,
            due_date=task.due_date,
            remind_at=task.remind_at,
            my_day=task.my_day_date == today,
            completed=task.completed_at is not None,
            completed_at=task.completed_at,
            created_at=task.created_at,
            updated_at=task.updated_at,
        )


class VoiceResult(BaseModel):
    entry_id: uuid.UUID
    raw_text: str | None
    tasks: list[TaskOut]


class TaskCreate(BaseModel):
    """Typed task. `id` is generated by the app so a resend never creates a duplicate."""

    model_config = ConfigDict(extra="forbid")

    id: uuid.UUID
    title: Title
    note: str | None = None
    starred: bool = False
    due_date: date | None = None
    remind_at: AwareDatetime | None = None
    my_day: bool = False


class TaskPatch(BaseModel):
    """Omitted fields stay unchanged. note, due_date and remind_at may be set to null."""

    model_config = ConfigDict(extra="forbid")

    title: Title = None
    note: str | None = None
    starred: bool = None
    due_date: date | None = None
    remind_at: AwareDatetime | None = None
    my_day: bool = None
    completed: bool = None

    @field_validator("title", "starred", "my_day", "completed", mode="before")
    @classmethod
    def not_null(cls, v):
        if v is None:
            raise ValueError("không được để trống")
        return v
